export function oneGForUnits(length: string, time: string): { value: number; unitLabel: string } {
  const l = length.trim().toLowerCase();
  const t = time.trim().toLowerCase();
  const lenFactor = l === "m" ? 1 : l === "cm" ? 100 : 1000; // meters -> target length
  const timeFactor = t === "ms" ? 1000 : 1; // seconds -> target time
  const gVal = 9.80665 * (lenFactor / (timeFactor * timeFactor));
  // Round cleanly to 8 significant digits to avoid IEEE float noise like 0.009806650000000001
  const rounded = Number(gVal.toPrecision(8));
  return {
    value: rounded,
    unitLabel: `${l}/${t}²`,
  };
}
