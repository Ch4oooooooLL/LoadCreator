#Requires -Version 5.1
<#
.SYNOPSIS
  One-click build of the LoadCreator Windows installer (.exe) with a timestamp in the filename.

.DESCRIPTION
  - Runs: npm run tauri build   (frontend build + Rust release compile + NSIS packaging)
  - Copies the produced *-setup.exe into output\installers\ as
      <Product>_<version>_<arch>_setup_<timestamp>.exe
  - By default cleans intermediate artifacts created by this packaging run
      (dist\, the NSIS working dir, and the un-timestamped original installer).

.PARAMETER SkipBuild
  Skip "tauri build" and just process the newest existing installer (for verifying this script).

.PARAMETER KeepIntermediates
  Keep intermediate artifacts (dist\, NSIS working dir, original installer).

.PARAMETER OutputDir
  Output directory for the final installer, relative to the repo root. Default: output\installers

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File .\package-exe.ps1

.EXAMPLE
  .\package-exe.bat -KeepIntermediates
#>
[CmdletBinding()]
param(
    [switch]$SkipBuild,
    [switch]$KeepIntermediates,
    [string]$OutputDir = "output\installers"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $root

function Fail([string]$msg) {
    Write-Host "[package-exe] ERROR: $msg" -ForegroundColor Red
    exit 1
}

function Step([string]$msg) {
    Write-Host "[package-exe] $msg" -ForegroundColor Cyan
}

function Cleanup-Intermediates([string]$srcInstaller) {
    if ($KeepIntermediates) {
        Write-Host "[package-exe] KeepIntermediates: intermediates kept." -ForegroundColor DarkGray
        return
    }
    Write-Host "[package-exe] Cleaning temporary packaging artifacts ..." -ForegroundColor DarkGray

    # 1) The un-timestamped installer produced by this run (already copied out).
    if ($srcInstaller -and (Test-Path -LiteralPath $srcInstaller)) {
        Remove-Item -LiteralPath $srcInstaller -Force -ErrorAction SilentlyContinue
    }

    # 2) NSIS packaging working directory (temporary scripts/files).
    $nsisWork = Join-Path $root "src-tauri\target\release\nsis"
    if (Test-Path -LiteralPath $nsisWork) {
        Remove-Item -LiteralPath $nsisWork -Recurse -Force -ErrorAction SilentlyContinue
    }

    # 3) Frontend build output dist\ (regenerated by beforeBuildCommand on each build).
    $dist = Join-Path $root "dist"
    if (Test-Path -LiteralPath $dist) {
        Remove-Item -LiteralPath $dist -Recurse -Force -ErrorAction SilentlyContinue
    }

    # 4) Leftover NSIS zip archives.
    $bundleDir = Join-Path $root "src-tauri\target\release\bundle\nsis"
    if (Test-Path -LiteralPath $bundleDir) {
        Get-ChildItem -LiteralPath $bundleDir -Filter "*.nsis.zip" -File -ErrorAction SilentlyContinue |
            Remove-Item -Force -ErrorAction SilentlyContinue
    }

    Write-Host "[package-exe] Temporary artifacts cleaned." -ForegroundColor DarkGray
}

try {
    # ---- ensure the Rust toolchain is discoverable ----------------------
    # cargo/rustc normally live in %USERPROFILE%\.cargo\bin, but that folder
    # is frequently absent from PATH when the .bat is launched by double-click
    # in Explorer. Without it, "tauri build" fails with:
    #   failed to run 'cargo metadata' ... program not found
    $cargoBin = Join-Path $env:USERPROFILE ".cargo\bin"
    if (Test-Path -LiteralPath $cargoBin) {
        if ((($env:PATH -split ';') -notcontains $cargoBin)) {
            $env:PATH = $cargoBin + ';' + $env:PATH
        }
    }
    if (-not (Get-Command cargo -ErrorAction SilentlyContinue)) {
        Fail ("cargo not found. Install the Rust toolchain from https://rustup.rs " +
              "or add %USERPROFILE%\.cargo\bin to PATH.")
    }

    # ---- read product info ----------------------------------------------
    $confPath = Join-Path $root "src-tauri\tauri.conf.json"
    if (-not (Test-Path -LiteralPath $confPath)) { Fail "config not found: $confPath" }
    $conf = Get-Content -LiteralPath $confPath -Raw -Encoding UTF8 | ConvertFrom-Json
    $product = if ($conf.productName) { [string]$conf.productName } else { "LoadCreator" }
    $version = if ($conf.version) { [string]$conf.version } else { "0.0.0" }

    # ---- timestamp ------------------------------------------------------
    $ts = Get-Date -Format "yyyyMMdd-HHmmss"

    # ---- build ----------------------------------------------------------
    if ($SkipBuild) {
        Write-Host "[package-exe] SkipBuild: skipping build, using newest existing installer." -ForegroundColor Yellow
    } else {
        Step "Building $product $version ..."
        & npm run tauri build
        if ($LASTEXITCODE -ne 0) { Fail "tauri build failed (exit $LASTEXITCODE)" }
    }

    # ---- locate newest installer ---------------------------------------
    $bundleDir = Join-Path $root "src-tauri\target\release\bundle\nsis"
    if (-not (Test-Path -LiteralPath $bundleDir)) {
        Fail "NSIS output dir not found: $bundleDir"
    }
    $setup = Get-ChildItem -LiteralPath $bundleDir -Filter "*-setup.exe" -File -ErrorAction SilentlyContinue |
        Sort-Object LastWriteTime -Descending | Select-Object -First 1
    if (-not $setup) { Fail "No *-setup.exe found in $bundleDir" }

    # ---- copy with timestamp -------------------------------------------
    $outPath = Join-Path $root $OutputDir
    New-Item -ItemType Directory -Force -Path $outPath | Out-Null
    $stem = [System.IO.Path]::GetFileNameWithoutExtension($setup.Name)   # e.g. LoadCreator_2.0.0_x64-setup
    $finalName = $stem + "_" + $ts + ".exe"
    $dest = Join-Path $outPath $finalName
    Copy-Item -LiteralPath $setup.FullName -Destination $dest -Force

    # ---- verify copy ----------------------------------------------------
    $srcLen = (Get-Item -LiteralPath $setup.FullName).Length
    $dstLen = (Get-Item -LiteralPath $dest).Length
    if ($dstLen -le 0 -or $dstLen -ne $srcLen) {
        Fail "copy verification failed (src $srcLen bytes / dst $dstLen bytes)"
    }

    $sizeMb = [math]::Round($dstLen / 1MB, 2)
    Write-Host ""
    Write-Host "[package-exe] Installer created:" -ForegroundColor Green
    Write-Host "    $dest" -ForegroundColor Green
    Write-Host "    size: $sizeMb MB" -ForegroundColor Green

    # ---- cleanup --------------------------------------------------------
    Cleanup-Intermediates $setup.FullName

    Write-Host "[package-exe] Done." -ForegroundColor Cyan
    exit 0
}
catch {
    Fail $_.Exception.Message
}
